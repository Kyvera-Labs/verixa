import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
  aggregateCoverage,
  generateHtmlDashboard,
  generateMarkdownSummary,
  parseLcovString,
  runCoverageMerge,
} from "../../infra/ci/coverage-merge.js";

const FIXTURE_LCOV_1 = `
TN:
SF:packages/pkg-a/src/a.ts
FN:1,funcA
FNDA:2,funcA
FNF:1
FNH:1
BRDA:5,0,0,1
BRDA:5,0,1,0
BRF:2
BRH:1
DA:1,2
DA:2,2
DA:3,0
LF:3
LH:2
end_of_record
`;

const FIXTURE_LCOV_2 = `
TN:
SF:packages/pkg-b/src/b.ts
FN:10,funcB
FNDA:1,funcB
FNF:1
FNH:1
BRDA:12,0,0,1
BRDA:12,0,1,1
BRF:2
BRH:2
DA:10,1
DA:11,1
DA:12,1
LF:3
LH:3
end_of_record
`;

describe("coverage-merge (Issue 412)", () => {
  const tmpDir = path.join(process.cwd(), "tests/ci/helpers/__tmp_coverage_test__");

  beforeEach(() => {
    rmSync(tmpDir, { recursive: true, force: true });
    mkdirSync(tmpDir, { recursive: true });
  });

  afterEach(() => {
    rmSync(tmpDir, { recursive: true, force: true });
  });

  it("parses single and multiple LCOV file records into CoverageEntry metrics", () => {
    const parsed = parseLcovString(FIXTURE_LCOV_1);

    expect(parsed["packages/pkg-a/src/a.ts"]).toBeDefined();
    const entry = parsed["packages/pkg-a/src/a.ts"];
    if (entry) {
      expect(entry.lines.total).toBe(3);
      expect(entry.lines.covered).toBe(2);
      expect(entry.lines.pct).toBe(66.67);

      expect(entry.functions.total).toBe(1);
      expect(entry.functions.covered).toBe(1);
      expect(entry.functions.pct).toBe(100);

      expect(entry.branches.total).toBe(2);
      expect(entry.branches.covered).toBe(1);
      expect(entry.branches.pct).toBe(50);
    }
  });

  it("aggregates per-package files into monorepo and package-level summaries", () => {
    const pkgA = {
      name: "packages/pkg-a",
      files: parseLcovString(FIXTURE_LCOV_1),
    };
    const pkgB = {
      name: "packages/pkg-b",
      files: parseLcovString(FIXTURE_LCOV_2),
    };

    const report = aggregateCoverage([pkgA, pkgB]);

    expect(report.totalFiles).toBe(2);

    // Lines: 2/3 + 3/3 = 5/6 = 83.33%
    expect(report.aggregate.lines.total).toBe(6);
    expect(report.aggregate.lines.covered).toBe(5);
    expect(report.aggregate.lines.pct).toBe(83.33);

    // Branches: 1/2 + 2/2 = 3/4 = 75.00%
    expect(report.aggregate.branches.total).toBe(4);
    expect(report.aggregate.branches.covered).toBe(3);
    expect(report.aggregate.branches.pct).toBe(75);

    // Packages breakdown
    expect(report.packages["packages/pkg-a"]?.lines.pct).toBe(66.67);
    expect(report.packages["packages/pkg-b"]?.lines.pct).toBe(100);
  });

  it("formats Markdown summary table containing aggregate and per-package breakdown", () => {
    const pkgA = {
      name: "packages/pkg-a",
      files: parseLcovString(FIXTURE_LCOV_1),
    };
    const report = aggregateCoverage([pkgA]);

    const md = generateMarkdownSummary(report);

    expect(md).toContain("## 📊 Workspace Coverage Aggregate Report");
    expect(md).toContain("| **Lines** |");
    expect(md).toContain("`packages/pkg-a`");
    expect(md).toContain("Generated by `infra/ci/coverage-merge.ts`");
  });

  it("formats HTML dashboard with statistics cards and package rows", () => {
    const pkgA = {
      name: "packages/pkg-a",
      files: parseLcovString(FIXTURE_LCOV_1),
    };
    const report = aggregateCoverage([pkgA]);

    const html = generateHtmlDashboard(report);

    expect(html).toContain("<!DOCTYPE html>");
    expect(html).toContain("Verixa Monorepo Coverage Dashboard");
    expect(html).toContain("packages/pkg-a");
  });

  it("runCoverageMerge discovers package lcov files and writes merged outputs", () => {
    // Setup simulated monorepo in tmpDir
    const pkgADir = path.join(tmpDir, "packages/pkg-a/coverage");
    const pkgBDir = path.join(tmpDir, "packages/pkg-b/coverage");
    mkdirSync(pkgADir, { recursive: true });
    mkdirSync(pkgBDir, { recursive: true });

    writeFileSync(path.join(pkgADir, "lcov.info"), FIXTURE_LCOV_1);
    writeFileSync(path.join(pkgBDir, "lcov.info"), FIXTURE_LCOV_2);
    writeFileSync(
      path.join(tmpDir, "packages/pkg-a/package.json"),
      JSON.stringify({ name: "@verixa/pkg-a" }),
    );
    writeFileSync(
      path.join(tmpDir, "packages/pkg-b/package.json"),
      JSON.stringify({ name: "@verixa/pkg-b" }),
    );

    const outDir = path.join(tmpDir, "merged_output");
    const mdSummary = path.join(tmpDir, "summary.md");

    const report = runCoverageMerge({
      repoRoot: tmpDir,
      outputDir: outDir,
      markdownSummaryPath: mdSummary,
    });

    expect(report.totalFiles).toBe(2);
    expect(report.aggregate.lines.pct).toBe(83.33);

    const summary = JSON.parse(
      readFileSync(path.join(outDir, "coverage-summary.json"), "utf8"),
    ) as {
      total: { lines: { pct: number } };
      packages: Record<string, { lines: { pct: number } }>;
    };
    expect(summary.total.lines.pct).toBe(83.33);
    expect(summary.packages["@verixa/pkg-a"].lines.pct).toBe(66.67);
    expect(summary.packages["@verixa/pkg-b"].lines.pct).toBe(100);
  });
});
